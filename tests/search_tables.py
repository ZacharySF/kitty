"""The Python text facts the Rust search (server/src/search) needs, as this interpreter has them.

`server/src/search/tables.rs` is generated from here: which characters `str.isalnum()` accepts
(the word tokens of ``kitty.core.search.TOKEN``, ``[^\\W_]+``), ``str.isspace()`` and
``str.isdecimal()`` (what ``re``'s ``\\s`` and ``\\d`` match, and what ``int()`` reads),
``str.casefold()`` where it changes a character, and ``html.entities.html5`` (what
``html.unescape`` reads). Regenerate
it with ``uv run python tests/search_tables.py`` after a Python upgrade;
tests/test_search_parity.py fails while it is stale.
"""
from __future__ import annotations

import html.entities
import sys
import unicodedata
from pathlib import Path

TABLES = Path(__file__).resolve().parents[1] / "server/src/search/tables.rs"


def _ranges(predicate) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for code in range(0x110000):
        if 0xD800 <= code <= 0xDFFF:
            continue
        if predicate(chr(code)):
            if out and out[-1][1] == code - 1:
                out[-1] = (out[-1][0], code)
            else:
                out.append((code, code))
    return out


def _rust(text: str) -> str:
    return '"' + "".join(c if 0x20 <= ord(c) < 0x7f and c not in '"\\' else f"\\u{{{ord(c):x}}}" for c in text) + '"'


def _rows(items: list[str], per_row: int) -> list[str]:
    return ["    " + " ".join(items[start:start + per_row]) for start in range(0, len(items), per_row)]


def tables() -> str:
    alnum = _ranges(str.isalnum)
    folds = [(code, chr(code).casefold()) for code in range(0x110000)
             if not 0xD800 <= code <= 0xDFFF and chr(code).casefold() != chr(code)]
    entities = sorted(html.entities.html5.items())
    return "\n".join([
        f"//! Text facts as CPython {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}) has them.",
        "//! Generated by tests/search_tables.py (`uv run python tests/search_tables.py`); do not edit.",
        "",
        "/// `str.isalnum()` of one character: inclusive, sorted ranges.",
        "pub static ALNUM: &[(u32, u32)] = &[",
        *_rows([f"(0x{start:x}, 0x{end:x})," for start, end in alnum], 6),
        "];",
        "",
        "/// `str.isspace()` of one character (also what `str.strip()` and `str.split()` take as whitespace).",
        "pub static SPACE: &[(u32, u32)] = &[",
        *_rows([f"(0x{start:x}, 0x{end:x})," for start, end in _ranges(str.isspace)], 6),
        "];",
        "",
        "/// `str.isdecimal()` of one character (`re`'s `\\d`, the digits `int()` reads); each range",
        "/// runs from a zero in steps of ten digits.",
        "pub static DECIMAL: &[(u32, u32)] = &[",
        *_rows([f"(0x{start:x}, 0x{end:x})," for start, end in _ranges(str.isdecimal)], 6),
        "];",
        "",
        "/// `str.casefold()` of one character, where it changes it; sorted by character.",
        "pub static CASEFOLD: &[(u32, &str)] = &[",
        *_rows([f"(0x{code:x}, {_rust(folded)})," for code, folded in folds], 6),
        "];",
        "",
        "/// `html.entities.html5`: every named character reference (with and without `;`), sorted.",
        "pub static HTML5: &[(&str, &str)] = &[",
        *_rows([f"({_rust(name)}, {_rust(value)})," for name, value in entities], 4),
        "];",
        "",
    ])


if __name__ == "__main__":
    TABLES.parent.mkdir(parents=True, exist_ok=True)
    TABLES.write_text(tables(), encoding="utf-8")
