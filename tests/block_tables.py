"""CPython's additional block text facts; regenerate with uv run python tests/block_tables.py."""
from __future__ import annotations

import _sre
import sys
import unicodedata
from pathlib import Path
from re._casefix import _EXTRA_CASES

from search_tables import _ranges, _rows

TABLES = Path(__file__).resolve().parents[1] / "server/src/blocks/tables.rs"


def tables() -> str:
    lower = [(c, _sre.unicode_tolower(c)) for c in range(0x110000)
             if not 0xD800 <= c <= 0xDFFF and _sre.unicode_tolower(c) != c]
    fixes = sorted((c, other) for c, others in _EXTRA_CASES.items() for other in others)
    out = [
        f"//! Text facts as CPython {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}) has them.",
        "//! Generated by tests/block_tables.py (`uv run python tests/block_tables.py`); do not edit.",
        "",
    ]
    for name, rows in (("PRINTABLE", _ranges(str.isprintable)),
                       ("CASED", _ranges(lambda c: _sre.unicode_iscased(ord(c)))),
                       ("LOWER", lower), ("CASE_FIXES", fixes)):
        out += [f"pub static {name}: &[(u32, u32)] = &[",
                *_rows([f"(0x{a:x}, 0x{b:x})," for a, b in rows], 6), "];", ""]
    return "\n".join(out)


if __name__ == "__main__":
    TABLES.write_text(tables(), encoding="utf-8")
