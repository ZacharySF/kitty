# The Unicode tables ----------------------------------------------------------------------

def _ranges(predicate) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for code in range(0x110000):
        if predicate(chr(code)):
            if out and out[-1][1] == code - 1:
                out[-1] = (out[-1][0], code)
            else:
                out.append((code, code))
    return out


def _sigma_final(text: str) -> bool:
    return text.lower()[-1] == "\u03c2"


def unicode_tables() -> str:
    """The text of server/src/builds/unicode.rs for this interpreter."""
    def table(name: str, doc: str, ranges: list[tuple[int, int]]) -> list[str]:
        lines = [f"/// {doc}", f"pub static {name}: &[(u32, u32)] = &["]
        row: list[str] = []
        for start, end in ranges:
            row.append(f"(0x{start:x}, 0x{end:x}),")
            if len(row) == 6:
                lines.append("    " + " ".join(row))
                row = []
        if row:
            lines.append("    " + " ".join(row))
        lines.append("];")
        return lines

    lower = [(code, ord(chr(code).lower())) for code in range(0x110000)
             if code not in (0x130, 0x3A3) and chr(code).lower() != chr(code)]
    assert all(len(chr(code).lower()) == 1 for code, _ in lower)
    # Cased: Lowercase, Uppercase or Lt. Case-ignorable: probed through the final-sigma rule,
    # which is the only place str.lower consults it.
    cased = _ranges(lambda c: c.islower() or c.isupper() or c.istitle())
    ignorable = _ranges(lambda c: _sigma_final("A" + c + "\u03a3") and not _sigma_final("1" + c + "\u03a3"))
    lines = [
        f"//! Unicode facts as CPython {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}) has them.",
        "//! Generated by tests/test_build_reader_parity.py (`uv run python tests/test_build_reader_parity.py`);",
        "//! do not edit. Ranges are inclusive and sorted.",
        "",
        *table("PRINTABLE", "`str.isprintable()` of one character.", _ranges(str.isprintable)),
        "",
        *table("DIGIT", "`str.isdigit()` of one character.", _ranges(str.isdigit)),
        "",
        *table("SPACE", "`str.isspace()` of one character (also what `str.strip()` removes).", _ranges(str.isspace)),
        "",
        *table("CASED", "Characters that are Lowercase, Uppercase or titlecase (`_PyUnicode_IsCased`).", cased),
        "",
        *table("CASE_IGNORABLE", "Case-ignorable characters (`_PyUnicode_IsCaseIgnorable`).", ignorable),
        "",
        "/// `str.lower()` of one character, where it changes and is one character (U+0130 and U+03A3 aside).",
        "pub static LOWER: &[(u32, u32)] = &[",
    ]
    row = []
    for code, low in lower:
        row.append(f"(0x{code:x}, 0x{low:x}),")
        if len(row) == 6:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("];")
    return "\n".join(lines) + "\n"


def test_the_rust_unicode_tables_match_this_python():
    assert UNICODE_TABLES.read_text(encoding="utf-8") == unicode_tables(), \
        "server/src/builds/unicode.rs is stale: run `uv run python tests/test_build_reader_parity.py`"


