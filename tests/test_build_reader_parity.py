"""The Rust build reader (server/src/builds) against kitty.core.builds.document, case by case.

`rika-server check-build` (test-only) reads a build file's text on stdin and prints what the
Rust reader makes of it; every case here must come out exactly as `document.check` has it:
the same problems (message, line, column, path, severity, order), the same normalized build
(key order and int/float included), and the same exception where Python raises.

The corpus: every text tests/test_builds.py checks (recorded by running it), its CSS samples,
the schema defaults, every theme, and generated mutations: wrong types at every schema path,
bounds, patterns, unknown and duplicate keys at every level, NaN/Infinity, hex tokens, the CSS
policy, oversize input, invalid JSON at many positions, deep nesting, non-object documents and
schema versions.

The Rust reader also needs a few Unicode facts exactly as this Python has them (what
`str.isprintable`, `str.isdigit`, `str.isspace` and `str.lower` say); they live in
server/src/builds/unicode.rs, generated from this interpreter. Regenerate it with
`uv run python tests/test_build_reader_parity.py` after a Python upgrade.
"""
