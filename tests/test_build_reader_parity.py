def _python(text: str) -> dict:
    from kitty.core.builds import document

    try:
        checked = document.check(text)
    except Exception as exc:  # noqa: BLE001 - the exception's type is the expected outcome
        return {"raises": type(exc).__name__}
    return {"ok": checked.ok, "build": json.dumps(checked.build),
            "problems": [problem.as_dict() for problem in checked.problems]}


def _rust(text: str) -> dict:
    run = subprocess.run([str(RIKA_SERVER), "check-build"], input=text.encode("utf-8", "surrogatepass"),
                         capture_output=True, timeout=120)
    if run.returncode != 0:
        return {"failed": run.returncode, "stderr": run.stderr.decode(errors="replace")[-2000:]}
    out = json.loads(run.stdout)
    if "build" in out:
        out["build"] = json.dumps(out["build"])
    return out


def _show(text: str) -> str:
    return repr(text if len(text) < 300 else text[:200] + f"...<{len(text)} chars>..." + text[-60:])


@pytest.mark.skipif(not RIKA_SERVER.exists(), reason="build the server first: cargo build --release")
def test_the_rust_build_reader_matches_python_on_every_case():
    cases = list(dict.fromkeys(_cases()))
    assert len(cases) > 1000
    expected = [_python(text) for text in cases]
    with ThreadPoolExecutor(max_workers=os.cpu_count() or 4) as pool:
        actual = list(pool.map(_rust, cases))
    mismatches = [(text, want, got) for text, want, got in zip(cases, expected, actual) if want != got]
    report = "\n\n".join(f"{_show(text)}\n  python: {want}\n  rust:   {got}" for text, want, got in mismatches[:15])
    assert not mismatches, f"{len(mismatches)} of {len(cases)} cases differ:\n\n{report}"


